#!/usr/bin/env python3
"""
png_to_bitmap.py — 把图片转成 ESP32/OLED 可用的 C bitmap 数组

支持输入: PNG / BMP / ICO / GIF (PIL 能打开的都行)
支持输出: 1-bit 单色 (OLED/SSD1306 专用)

用法示例:
    # 基本：转成 12×12 单色 WiFi 图标
    python3 png_to_bitmap.py wifi.png --size 12x12 --mono --name wifi_icon

    # 指定输出文件和阈值
    python3 png_to_bitmap.py battery.png -s 16x16 --mono -t 128 -o battery_icon.h

    # 批量转换 (PowerShell)
    Get-ChildItem *.png | ForEach-Object { python3 png_to_bitmap.py $_ --mono -s 12x12 }

依赖: Pillow  (pip install Pillow)
"""

import argparse
import os
import sys
from pathlib import Path

try:
    from PIL import Image, ImageOps
except ImportError:
    print("❌ 缺少依赖 Pillow，请先装: pip install Pillow", file=sys.stderr)
    sys.exit(1)


def resize_image(img: Image.Image, target_w: int, target_h: int) -> Image.Image:
    """按目标尺寸缩放，保持比例（居中裁剪）"""
    if img.size == (target_w, target_h):
        return img
    # 先等比缩放，再居中裁剪
    ratio = max(target_w / img.width, target_h / img.height)
    new_size = (max(1, int(img.width * ratio)), max(1, int(img.height * ratio)))
    img = img.resize(new_size, Image.LANCZOS)
    # 居中裁剪
    left = (img.width - target_w) // 2
    top = (img.height - target_h) // 2
    return img.crop((left, top, left + target_w, top + target_h))


def to_monochrome(img: Image.Image, threshold: int = 128) -> Image.Image:
    """转灰度 → 按阈值转 1-bit 黑白"""
    # 转 RGB（如果是 RGBA 就把透明像素填成白色）
    if img.mode == "RGBA":
        bg = Image.new("RGB", img.size, (255, 255, 255))
        bg.paste(img, mask=img.split()[3])
        img = bg
    elif img.mode != "RGB":
        img = img.convert("RGB")

    # 灰度
    gray = ImageOps.grayscale(img)

    # 阈值转黑白：>=threshold → 白(1), <threshold → 黑(0)
    return gray.point(lambda x: 255 if x >= threshold else 0, mode="1")


def bits_to_bytes(img: Image.Image, w: int, h: int) -> bytearray:
    """
    把 1-bit 图像转成 U8g2/TFT_eSPI drawBitmap 要求的字节序列

    格式: 行优先, 水平字节, MSB first (两库 drawBitmap 统一):
      每 8 个水平像素 = 1 字节 (MSB = 最左)
      每行有 ceil(w/8) 字节
      按行顺序排列 (row 0, row 1, ..., row h-1)

    例如 12×12 图像: 12 行 × 2 字节/行 = 24 字节
    """
    assert img.mode == "1"
    pixels = img.load()

    bytes_per_row = (w + 7) // 8
    out = bytearray(h * bytes_per_row)

    for row in range(h):
        for byte_idx in range(bytes_per_row):
            byte_val = 0
            for bit in range(8):
                col = byte_idx * 8 + bit
                if col >= w:
                    continue
                # 1-bit 图像: 0=黑, 255=白
                # U8g2/TFT_eSPI bitmap: 1=亮点, 0=灭点
                p = pixels[col, row]
                if p == 0:  # 原图像是黑色 → 绘制亮点
                    byte_val |= (1 << (7 - bit))
            out[row * bytes_per_row + byte_idx] = byte_val

    return out


def bytes_to_c_array(data: bytes, var_name: str, w: int, h: int,
                      cols: int = 12) -> str:
    """字节序列 → C 数组字符串"""
    lines = [
        f"// Auto-generated by png_to_bitmap.py",
        f"// Source: {var_name}",
        f"// Size: {w} x {h} pixels, monochrome",
        f"// Format: U8g2/TFT_eSPI drawBitmap (MSB, horizontal bytes)",
        f"// Bytes: {len(data)} ({h} rows × {(w + 7) // 8} bytes/row)",
        f"",
        f"static const uint8_t {var_name}_data[{len(data)}] = {{",
    ]

    # 每行 cols 个字节
    for i in range(0, len(data), cols):
        chunk = data[i:i + cols]
        hex_str = ", ".join(f"0x{b:02X}" for b in chunk)
        comma = "," if i + cols < len(data) else ""
        lines.append(f"    {hex_str}{comma}")

    lines.append("};")
    lines.append("")
    lines.append(f"// 便捷描述结构体，可直接传 oled_set_status_icon()")
    lines.append(f"typedef struct {{")
    lines.append(f"    const uint8_t *data;")
    lines.append(f"    uint8_t w;")
    lines.append(f"    uint8_t h;")
    lines.append(f"}} oled_icon_t;")
    lines.append("")
    lines.append(f"static const oled_icon_t {var_name} = {{")
    lines.append(f"    .data = {var_name}_data,")
    lines.append(f"    .w = {w},")
    lines.append(f"    .h = {h},")
    lines.append(f"}};")
    lines.append("")

    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(
        description="""
┌─────────────────────────────────────────────────────────┐
│   png_to_bitmap.py  —  图片 → ESP32 OLED C bitmap 数组    │
│                                                         │
│   支持输入: PNG / ICO / BMP / GIF / WebP (Pillow 能开的都行)│
│   支持输出: 1-bit 单色  (SSD1306 / SH1106 / ST7789 / ILI9341 等)│
│   输出格式: U8g2 + TFT_eSPI 通用 (MSB first, 行优先, 水平字节)    │
└─────────────────────────────────────────────────────────┘

【依赖】
  pip install Pillow

【ICO 文件说明】
  ICO 是 Windows 图标容器，内含多张不同尺寸的图 (16x16 / 32x32 / 128x128 ...)。
  本工具自动取第 0 帧。建议用在线工具 (javl.github.io/image2cpp) 从 ICO 里
  导出一张目标尺寸的 PNG，再用本工具转 bitmap。

【OLED 尺寸建议】
  128×32 OLED (0.91") 推荐图标尺寸: 12×12 或 16×16
  128×64 OLED (1.3")   推荐图标尺寸: 16×16 或 24×24

【阈值 -t 说明】
  灰度图按阈值切黑白: 灰度 >= 阈值 → 白, < 阈值 → 黑
  取值 0-255, 默认 128
    阈值低 (如 50) → 更多像素变白色, 适合深色背景上的浅色图标
    阈值高 (如 200) → 更多像素变黑色, 适合浅色背景上的深色图标
  PNG 带透明通道时: 透明区域自动填白色 (OLED 背景)

【输出格式】
  生成的 C 代码包含两部分:
    1. xxx_data[]   — bitmap 字节数组 (U8g2 + TFT_eSPI 通用 drawBitmap 格式)
    2. oled_icon_t xxx — 便捷结构体 (含 .data .w .h, 可直接传 oled_set_status_icon())
  drawBitmap 格式: MSB first, 每 8 个水平像素 = 1 字节, 按行顺序排列
  例如 12×12 图标 = 12 行 × 2 字节/行 = 24 字节
""",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
【用法示例】

  # 基本: 转 12x12 单色 WiFi 图标, 输出到终端
  python tools/png_to_bitmap.py wifi.png -s 12x12

  # 指定 C 数组名 + 输出文件
  python tools/png_to_bitmap.py battery.ico -s 16x16 -n icon_battery -o icons/battery.h

  # 调整阈值 (深色图标用 200, 浅色图标用 80)
  python tools/png_to_bitmap.py signal.png -s 12x12 -t 200

  # 批量转换 (PowerShell)
  New-Item -ItemType Directory -Force icons | Out-Null
  Get-ChildItem *.png | ForEach-Object {
      python tools/png_to_bitmap.py $_ -s 12x12 -o "icons/$($_.BaseName).h"
  }

  # 批量转换 (Linux / macOS bash)
  mkdir -p icons && for f in *.png; do
      python3 tools/png_to_bitmap.py "$f" -s 12x12 -o "icons/${f%.png}.h"
  done

【集成到项目】

  1. 把生成的 .h 文件丢到 src/display/icons/
  2. #include "icons/wifi.h"
  3. oled_set_status_icon(&wifi_icon);   // wifi_icon 是 oled_icon_t 类型
        """,
    )
    parser.add_argument("input", help="输入图片路径 (.png/.ico/.bmp/.gif/.webp ...)")
    parser.add_argument(
        "-s", "--size", required=True,
        help="输出尺寸, 格式 WIDTHxHEIGHT (例如 12x12, 16x16, 8x8)",
    )
    parser.add_argument(
        "-t", "--threshold", type=int, default=128,
        help="灰度转黑白阈值, 范围 0-255, 默认 128。越小越多白, 越大越多黑",
    )
    parser.add_argument(
        "-n", "--name", default=None,
        help="C 数组名, 默认用输入文件名 (例如 wifi.png → wifi)",
    )
    parser.add_argument(
        "-o", "--output", default=None,
        help="输出文件路径, 默认 stdout (例如 icons/wifi.h)",
    )

    args = parser.parse_args()

    # 解析尺寸
    try:
        w, h = map(int, args.size.lower().split("x"))
        if w <= 0 or h <= 0:
            raise ValueError
    except Exception:
        print(f"❌ 尺寸格式错误: {args.size}，应为 WIDTHxHEIGHT (例如 12x12)", file=sys.stderr)
        sys.exit(1)

    if w > 128 or h > 128:
        print(f"⚠️  尺寸 {w}x{h} 超出 OLED 常用范围 (≤32)，确认需要这么大？", file=sys.stderr)

    # 打开图片
    try:
        img = Image.open(args.input)
    except Exception as e:
        print(f"❌ 无法打开图片 {args.input}: {e}", file=sys.stderr)
        sys.exit(1)

    print(f"📥 输入: {args.input}  ({img.size[0]}×{img.size[1]}, mode={img.mode})")

    # ICO 可能含多帧，取第一帧
    if img.format == "ICO" and getattr(img, "n_frames", 1) > 1:
        print(f"   ↳ ICO 含 {img.n_frames} 帧，取第 0 帧")
        img = img.seek(0) or img.copy()

    # 缩放
    img = resize_image(img, w, h)
    print(f"📐 缩放: {img.size[0]}×{img.size[1]}")

    # 转单色 (固定 1-bit, U8g2/TFT_eSPI 通用格式)
    img = to_monochrome(img, args.threshold)
    print(f"🎨 单色化: 阈值={args.threshold}")

    # 生成字节数组
    raw = bits_to_bytes(img, w, h)
    print(f"📦 输出: {len(raw)} 字节 (U8g2+TFT_eSPI 通用格式)")

    # 确定数组名
    if args.name:
        var_name = args.name
    else:
        var_name = Path(args.input).stem.replace("-", "_").replace(".", "_")
    # 确保 C 合法
    if not var_name[0].isalpha() and var_name[0] != "_":
        var_name = "_" + var_name

    # 生成 C 代码
    c_code = bytes_to_c_array(raw, var_name, w, h)

    # 输出
    if args.output:
        out_path = Path(args.output)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(c_code, encoding="utf-8")
        print(f"✅ 写入 {out_path}")
    else:
        print(c_code)


if __name__ == "__main__":
    main()
